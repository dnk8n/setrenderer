def glyph_image(ch: str) -> np.ndarray:
    rows = GLYPHS.get(ch, GLYPHS[" "])
    img = np.zeros((7, 5, 4), np.uint8)
    for y, r in enumerate(rows):
        for x in range(5):
            if r & (1 << (4 - x)):
                img[y, x] = (255, 255, 255, 255)
    return img
